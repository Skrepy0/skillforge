"""DraftDocument -> .pptx，使用 python-pptx 生成演示文稿。

- draft.title 作为标题页
- 每个 section 一张 slide：heading 作为标题，body 按 \n 拆分为 bullet
- 空行跳过
- 异常统一包装为 RenderError

python-pptx 属于外部库，导入放在 render() 内部延迟加载，
避免核心依赖在没装 python-pptx 时也要求导入。

类型说明：python-pptx 的类型存根里 BaseShape 不声明 text_frame / text，
但运行时 has_text_frame 为 True 时 text_frame 一定存在。
_set_text() 集中处理这个关联，type: ignore 只出现一次。
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, Any, cast

from skillforge.shared.errors import RenderError
from skillforge.shared.types import DraftDocument

if TYPE_CHECKING:
    from pptx.shapes.base import BaseShape


def _split_lines(body: str) -> list[str]:
    return [line.strip() for line in body.split("\n") if line.strip()]


def _set_text(shape: BaseShape | None, text: str) -> bool:
    """给有文本框的形状设置文本；形状不存在或无文本框时返回 False。

    python-pptx 没有 py.typed，mypy 视其为 untyped；Pyright 走存根则
    不认识 BaseShape.text_frame。用 cast(Any, ...) 统一两边视图。
    """
    if shape is None or not shape.has_text_frame:
        return False
    cast(Any, shape).text_frame.text = text
    return True


class PptxRenderer:
    def render(self, draft: DraftDocument, out_path: Path) -> Path:
        try:
            from pptx import Presentation
            from pptx.util import Pt

            prs = Presentation()

            # 标题页
            title_slide = prs.slides.add_slide(prs.slide_layouts[0])
            _set_text(title_slide.shapes.title, draft.title or "Untitled")
            if len(title_slide.placeholders) > 1:
                _set_text(title_slide.placeholders[1], "Generated by SkillForge")

            # 每个 section 一张 slide
            body_layout = prs.slide_layouts[1]  # Title and Content
            for section in draft.sections:
                slide = prs.slides.add_slide(body_layout)
                _set_text(slide.shapes.title, section.get("heading", ""))

                lines = _split_lines(section.get("body", ""))
                body_shape = slide.placeholders[1]
                if not lines or not body_shape.has_text_frame:
                    continue

                text_frame = cast(Any, body_shape).text_frame
                text_frame.text = lines[0]
                for line in lines[1:]:
                    text_frame.add_paragraph().text = line

                for para in text_frame.paragraphs:
                    for run in para.runs:
                        run.font.size = Pt(20)

            out_path = Path(out_path)
            out_path.parent.mkdir(parents=True, exist_ok=True)
            prs.save(str(out_path))
        except Exception as exc:
            raise RenderError(f"pptx 渲染失败: {exc}") from exc
        return out_path
